// These do not follow naming conventions because they're generated by LD
extern const char _binary_src_splash_txt_start[];
extern const char _binary_src_splash_txt_end[];

// These are set at the END of the respective init functions and are meant to be
// used by other init functions
static Term *g_main_term = NULL;
static Vnode *g_main_tty_dev = NULL;
static Vfs *g_root_fs = NULL;

static Vfs *init_tmpfs(Vfs *rootfs) {
    Vnode *tmpfs_mountpoint = NULL;
    Vfs *tmpfs = NULL;
    verify(vfs_create(rootfs->root, "tmp", strlen("tmp"),
                      &VFS_ATTR(VNODE_TYPE_DIR), &tmpfs_mountpoint) == 0);
    verify(tmpfs_mount(tmpfs_mountpoint, &tmpfs) == 0);
    vfs_vnode_rel(tmpfs_mountpoint);
    return tmpfs;
}

void init_splash(void) {
#if CONFIG_LOG_SHOW_SPLASH
    log_putsn(_binary_src_splash_txt_start,
              _binary_src_splash_txt_end - _binary_src_splash_txt_start);
    log_puts("\n\n");
#endif
}

void init_memory(void) {
    pmm_init();
    mmu_init();
    vmm_init();
}

void init_filesystem(void) {
    tmpfs_init();
    Vfs *rootfs = NULL;
    verify(tmpfs_mount(NULL, &rootfs) == 0);

    init_tmpfs(rootfs);

    InfoFile *initrd = info_get_initrd();
    initrd_make(rootfs->root, initrd->address, initrd->size);

    Vfs *devfs = NULL;
    verify(devfs_init(rootfs, &devfs) == 0);

    g_root_fs = rootfs;
}

void init_tty(TermBackend (*new_backend)(void)) {
    Vnode *devtty = NULL;
    tty_devtty_init(&devtty);

#if CONFIG_TTY_MAX < 1
#error "cannot compile the kernel with less than 1 TTY"
#endif

    TermBackend main_tb = new_backend();
    Term *main_term = term_new(main_tb);
    term_set_fallback(main_term);

    Vnode *main_tty_dev = NULL;
    Tty *main_tty_data = NULL;
    tty_init_text(main_term, &main_tty_dev, &main_tty_data);
    term_init();
    console_init();
    console_add_tty(main_tty_data);

    for (usize i = 0; i < CONFIG_TTY_MAX - 1; i++) {
        TermBackend tb = new_backend();
        Term *term = term_new(tb);

        Vnode *tty_dev = NULL;
        Tty *tty_data = NULL;
        tty_init_text(term, &tty_dev, &tty_data);
        term_set_buffering(term, true);
        console_add_tty(tty_data);
    }

    pty_init();
    g_main_term = main_term;
    g_main_tty_dev = main_tty_dev;
}

void init_devices(void) {
    fbdev_init(NULL);
    null_init();
    profile_init();
}

// The config lists are NULL-terminated
static usize init_strs(const char *const *in, struct syscall_str *out_strs) {
    usize n = 0;
    for (; in[n] != NULL; n++) {
        out_strs[n] = (struct syscall_str){in[n], strlen(in[n])};
    }
    return n;
}

void init_pid1(void) {
    proc_init();
    syscall_futex_init();

    assert(g_root_fs != NULL);
    const char *const init_argv[] = {CONFIG_INIT_PATH, CONFIG_INIT_ARGV};
    const char *const init_envp[] = {CONFIG_INIT_ENV};
    struct syscall_str argv[sizeof(init_argv) / sizeof(*init_argv)];
    struct syscall_str envp[sizeof(init_envp) / sizeof(*init_envp)];
    usize argc = init_strs(init_argv, argv);
    usize envc = init_strs(init_envp, envp);

    Proc *proc = proc_new(NULL, 0, g_root_fs->root, g_root_fs->root);
    Thread *thread = thread_new(proc, NULL, 0, NULL);
    int elf_ret = elf64_prepare_proc(argv[0].str, argv[0].len, argv, argc, envp,
                                     envc, proc, &thread->ctx,
                                     &proc->vmm_context);

    if (elf_ret != 0) {
        panic(NULL, "unable to start init program at %s", CONFIG_INIT_PATH);
    }

    assert(g_main_tty_dev != NULL);
    File *stdfile = slab_alloc(sizeof(File));
    stdfile->vnode = g_main_tty_dev;
    stdfile->num_ref = 3;
    proc->num_running_threads = 1;
    proc->next_fd = 3;
    proc->max_fd = proc->next_fd;
    FileDesc stddesc = {.file = stdfile, .flags = 0};
    proc->fd[0] = stddesc;
    proc->fd[1] = stddesc;
    proc->fd[2] = stddesc;

    proc_new_session_nolock(proc, g_main_tty_dev);

    Cpu *curr_cpu = cpu_get();
    assert(curr_cpu != NULL);
    cpu_set_interrupt_stack(curr_cpu, thread->kernel_stack);
    curr_cpu->thread = thread;
    thread->cpu = curr_cpu;
    thread_transition_nolock(thread, THREAD_STATE_RUNNING);

    assert(proc != NULL);
    assert(proc->vmm_context != NULL);
    vmm_switch(proc->vmm_context);
    CONTEXT_RESTORE_EXTRA(thread->xctx);

    vmm_init_reaper();
    pmm_init_threads();

    assert(g_main_term != NULL);
    log_set_user_hook(NULL);
    term_enable(g_main_term);
    term_set_buffering(g_main_term, true);
    log_set_vnode(NULL);
    profiler_init();
    context_trampoline(&thread->ctx);
}
